# class & object in python.
'Class is a blueprint for creating objects.'


# Creating class
class student:
    name = "Suraj chouhan"

#creating object(instance)
s1 = student()
print(s1.name)

s2 = student()
print(s2.name)


#Car_class
class car:
    color = "Black"
    brand = "Mercedes"

car1 = car()
print(car1.color)
print(car1.brand)










