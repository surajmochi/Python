"""
Loops: loops are used for sequential traversal. for traversing list, string, tuples etc.

"""

# list
nums = [1,2,3,4,5]
for val in nums:
    print(val)

# can do skips too with the help of range (0,100,4) starts from 0 to 100 skips 4 digit each.


# tuple
tup = (1,2,3,4,5,6,7)
for num in tup:
    print(num)

# string 
str = "CadmuxAcademy"
for string in str:
    print(string)




